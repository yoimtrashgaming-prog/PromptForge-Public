/**
 * Section the two official MiniMax H3 guides into per-mode reference files.
 *
 *   node scripts/section-h3-references.mjs
 *
 * WHY THIS EXISTS
 *
 * h3's system prompt reached ~13,600 tokens on its default mode: house rules,
 * SKILL.md, and BOTH official guides, before a word of output. The guides are
 * right and we keep them — but a T2VA generation was carrying the entire
 * full-reference guide, and every mode was carrying four worked examples of
 * three other modes.
 *
 * WHAT DECIDES WHAT GETS DROPPED
 *
 * Not taste. The node that consumes our output — the DaSiWa MiniMax H3
 * Director, docs/minimax_h3_director.md — is the authority, the same tiebreak
 * server/references.mjs already applies to the label classes. Three drops,
 * each with the Director's own words behind it:
 *
 *   1. The base guide's section 2.1, the image-alignment instruction lines.
 *      The Director writes these itself: "Alignment instruction lines (for
 *      I2VA/FL2VA/L2VA) are generated automatically based on mode and
 *      duration; you do not type them manually." Teaching the model to write
 *      them produces a duplicate line in the final prompt, so this is a
 *      correctness fix that happens to save 222 tokens.
 *
 *   2. Every worked example in both guides — the base guide's four Cases and
 *      the reference guide's Complete Example. All five emit raw MiniMax
 *      field names (`integrated_multimodal_description: ...`), and the
 *      Director appends those headers itself: "Section headers
 *      (`subject_definitions:` etc.) are appended automatically by the
 *      backend; you write only the content." We parse `===SEGMENT: Label===`
 *      and SKILL.md's own example is the only one in that shape. The
 *      `segment_fields` map in config/models.yaml exists precisely because
 *      the 27B keeps prefixing bodies with those field names — that is this
 *      leaking through, already measured. ~2,040 tokens of counter-example.
 *
 *   3. The reference guide's sections 5.4 and 6 — speakers/dialogue and the
 *      two audio fields. Not deleted, moved: they duplicate base guide 4.4,
 *      4.6 and 4.7, which now live in the shared core every mode loads.
 *
 * Everything written here is VERBATIM from the source documents, sliced on
 * heading boundaries. Nothing is paraphrased and no field name is retyped —
 * README.md in the references directory is explicit that paraphrasing these
 * from memory is how you end up emitting field names the model does not
 * recognise, and that applies just as much to a build script.
 *
 * Idempotent, and safe to re-run after `npm run fetch-h3-refs` picks up an
 * upstream change. Slicing is anchored to heading TEXT rather than line
 * numbers, so an upstream edit that moves a section still works and one that
 * renames a section fails loudly instead of writing a truncated guide.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const DIR = 'prompts/video/h3/references';
const BASE = path.join(DIR, 'h3-base-official.md');
const REF = path.join(DIR, 'h3-reference-official.md');

/**
 * Lines of `doc` from the heading `from` up to (not including) `to`.
 *
 * Both anchors are matched as exact full lines. A missing anchor throws: the
 * failure that matters is writing a file that is silently missing a section,
 * because the model would simply produce worse output rather than error.
 */
function slice(doc, name, from, to) {
  const lines = doc.split('\n');
  const at = (h) => {
    const i = lines.indexOf(h);
    if (i === -1) throw new Error(`${name}: heading not found — ${JSON.stringify(h)}`);
    return i;
  };
  const start = at(from);
  const end = to == null ? lines.length : at(to);
  if (end <= start) throw new Error(`${name}: ${JSON.stringify(to)} precedes ${JSON.stringify(from)}`);
  return lines.slice(start, end).join('\n').trim();
}

const PROVENANCE = (src, what) =>
  `<!-- Verbatim from ${src}. ${what} Generated by scripts/section-h3-references.mjs — do not hand-edit; re-run the script. -->`;

const base = await readFile(BASE, 'utf8');
const ref = await readFile(REF, 'utf8');

// ── the shared core: every mode, whatever it is, writes shots and sound ──
//
// Base guide section 4 entire. It is titled "How to Write the Three Shared
// Core Sections" and that is exactly what it is — timeline, cuts, camera
// vocabulary, speakers and dialogue, on-screen text, and the two audio
// fields. None of it is mode-specific, and the reference guide's own
// equivalents (5.4 and 6) are thinner, which is why those get dropped there
// rather than here.
const core = [
  '# H3 core conventions — timeline, shots, camera, dialogue, sound',
  '',
  PROVENANCE(
    'h3-base-official.md section 4 ("How to Write the Three Shared Core Sections")',
    'Loaded in every H3 mode: none of it is mode-specific.'
  ),
  '',
  slice(base, 'core', '## 4. How to Write the Three Shared Core Sections', '## 5. Cases'),
].join('\n');

// ── base modes: T2VA / I2VA / FL2VA / L2VA ──
//
// Section 1 (what each mode is) and 2.2 (the three core fields), for all four.
// Section 3 (how a supplied keyframe enters the description) is split per
// mode below, 6 Oct 2026: each frame mode gets its own part and T2VA, which
// has no keyframe, gets none ("each section should be injected into said
// section"). Section 2.1 is deliberately absent — see the header of this
// file — and replaced, in each frame mode's file, by a statement of what the
// Director actually does with those lines, so the model knows the alignment
// line exists and knows not to write one.
const baseModes = [
  '# H3 base modes — T2VA / I2VA / FL2VA / L2VA',
  '',
  PROVENANCE(
    'h3-base-official.md sections 1 and 2.2',
    'Section 2.1 and the section 5 cases are omitted on purpose, and section 3 is loaded per mode from its own file.'
  ),
  '',
  slice(base, 'base:overview', '## 1. Task Overview', '## 2. Final Prompt Structure'),
  '',
  slice(
    base,
    'base:fields',
    '### 2.2 Part Two Contains the Three Core Fields',
    '## 3. How to Incorporate Keyframes into the Multimodal Description'
  ),
].join('\n');

const ALIGNMENT_NOTE = [
  '## The image-alignment line is not yours to write',
  '',
  'This prompt opens with a line stating how each supplied picture aligns',
  'with the target video timeline. **Do not write it.** The MiniMax H3',
  'Director generates it from the mode and the duration setting — its',
  'documentation is explicit that these lines "are generated automatically',
  'based on mode and duration; you do not type them manually." A prompt that',
  'includes one produces a duplicated instruction in the final output.',
  '',
  'Begin at the first core field. What the alignment line asserts is still',
  'true, and the section below is how you write forward from it.',
].join('\n');

const keyframeMode = (mode, from, to) => [
  `# H3 ${mode} — the keyframe`,
  '',
  PROVENANCE(`h3-base-official.md section ${from.match(/### (3\.\d)/)[1]}`, `Loaded only in ${mode}.`),
  '',
  ALIGNMENT_NOTE,
  '',
  slice(base, `base:${mode}`, from, to),
].join('\n');
const i2va = keyframeMode('I2VA', '### 3.1 I2VA: Begin from the Image and Develop Forward', '### 3.2 FL2VA: Describe the Path Between the First and Last Frames');
const fl2va = keyframeMode('FL2VA', '### 3.2 FL2VA: Describe the Path Between the First and Last Frames', '### 3.3 L2VA: Infer the Opening and Land on the Image at the End');
const l2va = keyframeMode('L2VA', '### 3.3 L2VA: Infer the Opening and Land on the Image at the End', '## 4. How to Write the Three Shared Core Sections');

// ── REF2VA, which our UI still calls "Full reference" ──
//
// The opening paragraphs and sections 1 through 5.3. Dropped: 5.4 and 6,
// which the shared core already covers from the base guide, and 7, the
// worked example.
//
// The opening was dropped too until 6 Oct 2026, because the slice began at
// "## 1." — and it holds the guide's one rule for detailed_description: "as
// detailed and explicit as possible", appearance, environment and light in
// every shot. Without it a Q6 wrote that field as one style sentence.
const ref2va = [
  '# H3 full-reference mode (the Director calls it REF2VA)',
  '',
  PROVENANCE(
    'h3-reference-official.md, its opening and sections 1 to 5.3',
    'Sections 5.4 and 6 are omitted because the shared core file covers the same ground from the base guide; section 7, the worked example, is omitted because it writes raw field names the Director appends itself.'
  ),
  '',
  slice(ref, 'ref:opening', '# Full-Reference Mode Rewrite Output Format Guide', '## 1. Overall Structure')
    .replace(/^# .*\n+/, ''),
  '',
  slice(ref, 'ref:body', '## 1. Overall Structure', '### 5.4 Speakers, Audio Sources, and Dialogue'),
].join('\n');

const OUT = [
  ['h3-core.md', core],
  ['h3-base-modes.md', baseModes],
  ['h3-i2va.md', i2va],
  ['h3-fl2va.md', fl2va],
  ['h3-l2va.md', l2va],
  ['h3-ref2va.md', ref2va],
];

const tok = (s) => Math.round(s.length / 4.25);
console.log(`  source   h3-base-official.md       ${base.trim().length} ch  ~${tok(base.trim())} tok`);
console.log(`  source   h3-reference-official.md  ${ref.trim().length} ch  ~${tok(ref.trim())} tok`);
console.log('');
for (const [name, text] of OUT) {
  // fs, never PowerShell Set-Content, and LF only — see CLAUDE.md.
  await writeFile(path.join(DIR, name), `${text.replace(/\r\n/g, '\n').trim()}\n`, 'utf8');
  console.log(`  wrote    ${name.padEnd(20)} ${text.trim().length} ch  ~${tok(text.trim())} tok`);
}
console.log('\nRestart the server to load them.');
